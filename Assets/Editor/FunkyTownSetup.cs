    }

    [MenuItem("Tools/Funky Town/1c Apply Music only (clip + tempo)")]
    public static void ApplyMusic()
    {
        Scene scene = OpenScene();
        AudioClip clip = LoadMusic();
        if (clip == null) return;

        List<Transform> roots = scene.GetRootGameObjects()
            .SelectMany(r => r.GetComponentsInChildren<Transform>(true)).Where(t => t.name == RootName).ToList();
        if (roots.Count == 0)
        {
            Debug.LogError($"Funky Town: no '{RootName}' object found. Run '1 Setup Party' first.");
            return;
        }

        int lights = 0, fountains = 0;
        foreach (Transform root in roots)
        {
            AudioSource source = root.GetComponent<AudioSource>();
            if (source != null)
            {
                source.clip = clip;
                source.volume = MusicVolume;
                EditorUtility.SetDirty(source);
            }
            foreach (PartyLight light in root.GetComponentsInChildren<PartyLight>(true))
            {
                Configure(light, ("beatsPerMinute", MusicBpm));
                lights++;
            }
            ParticleSystem[] systems = root.GetComponentsInChildren<ParticleSystem>(true)
                .Where(p => p.name.StartsWith("Fountain")).OrderBy(p => p.name).ToArray();
            for (int i = 0; i < systems.Length; i++)
            {
                SetFountainTiming(systems[i], i);
                EditorUtility.SetDirty(systems[i]);
                fountains++;
            }
        }

        EditorSceneManager.MarkSceneDirty(scene);
        EditorSceneManager.SaveScene(scene);
        Debug.Log($"Funky Town: music '{clip.name}' assigned at volume {MusicVolume}, {MusicBpm} BPM applied to {lights} lights and {fountains} fountains.");
    }

    [MenuItem("Tools/Funky Town/2 Mark Static + Bake Occlusion Culling")]
    public static void OptimizePerformance()
    {
        Scene scene = OpenScene();
        int marked = 0, skipped = 0;

        foreach (GameObject sceneRoot in scene.GetRootGameObjects())
        {
            foreach (MeshRenderer renderer in sceneRoot.GetComponentsInChildren<MeshRenderer>(true))
            {
                GameObject go = renderer.gameObject;
                if (IsDynamic(go.transform))
                {
                    skipped++;
                    continue;
                }

                // Transparent objects must not hide what is behind them.
                bool opaque = renderer.sharedMaterials.All(m => m != null && m.renderQueue < (int)RenderQueue.AlphaTest);
                StaticEditorFlags flags = StaticEditorFlags.BatchingStatic | StaticEditorFlags.OccludeeStatic;
                if (opaque) flags |= StaticEditorFlags.OccluderStatic;

                GameObjectUtility.SetStaticEditorFlags(go, GameObjectUtility.GetStaticEditorFlags(go) | flags);
                marked++;
            }
        }

        EditorSceneManager.MarkSceneDirty(scene);
        EditorSceneManager.SaveScene(scene);
        Debug.Log($"Funky Town: {marked} renderers marked static, {skipped} dynamic renderers skipped.");

        bool baked = StaticOcclusionCulling.Compute();
        EditorSceneManager.SaveScene(scene);
        Debug.Log($"Funky Town: occlusion culling bake {(baked ? "succeeded" : "FAILED")}, data size {StaticOcclusionCulling.umbraDataSize} bytes.");
    }

    [MenuItem("Tools/Funky Town/3 Apply Player Settings (name, icon, splash)")]
    public static void ApplyPlayerSettings()
    {
        Texture2D icon = EnsureTexture(IconPath, 512, DiscoBallPixel, false);
        Texture2D splash = EnsureTexture(SplashPath, 512, DiscoBallPixel, true);
        Sprite splashSprite = AssetDatabase.LoadAssetAtPath<Sprite>(SplashPath);

        PlayerSettings.productName = "Funky Town";
        PlayerSettings.companyName = "Windisch Vogl";
        PlayerSettings.SetApplicationIdentifier(NamedBuildTarget.Standalone, "com.windischvogl.funkytown");
        PlayerSettings.SetIcons(NamedBuildTarget.Unknown, new[] { icon }, IconKind.Any);

        // Own splash screen instead of the default Unity one.
        PlayerSettings.SplashScreen.show = true;
        PlayerSettings.SplashScreen.showUnityLogo = false;
        PlayerSettings.SplashScreen.backgroundColor = new Color(0.07f, 0.03f, 0.13f);
        PlayerSettings.SplashScreen.logos = new[] { PlayerSettings.SplashScreenLogo.Create(2.5f, splashSprite) };

        AssetDatabase.SaveAssets();
        Debug.Log($"Funky Town: player settings applied (icon {icon != null}, splash {splash != null && splashSprite != null}).");
    }

    [MenuItem("Tools/Funky Town/4 Build macOS Player")]
    public static void Build()
    {
        BuildFor(BuildTarget.StandaloneOSX, BuildPath);
    }

    [MenuItem("Tools/Funky Town/5 Build Windows Player")]
    public static void BuildWindows()
    {
        if (!BuildPipeline.IsBuildTargetSupported(BuildTargetGroup.Standalone, BuildTarget.StandaloneWindows64))
        {
            Debug.LogError("Funky Town: Windows build support is not installed (Unity Hub > Installs > Add modules), " +
                           "or the editor was not restarted after installing it.");
            if (Application.isBatchMode) EditorApplication.Exit(1);
            return;
        }
        BuildFor(BuildTarget.StandaloneWindows64, WindowsBuildPath);
    }

    /// <summary>Batch mode entry point: both desktop builds.</summary>
    public static void BuildAll()
    {
        Build();
        BuildWindows();
    }

    private static void BuildFor(BuildTarget target, string path)
    {
        string[] scenes = EditorBuildSettings.scenes.Where(s => s.enabled).Select(s => s.path).ToArray();
        Directory.CreateDirectory(Path.GetDirectoryName(path));
        BuildReport report = BuildPipeline.BuildPlayer(scenes, path, target, BuildOptions.None);
        Debug.Log($"Funky Town: {target} build {report.summary.result}, {report.summary.totalSize / (1024 * 1024)} MB, " +
                  $"{report.summary.totalErrors} errors -> {path}");
        if (Application.isBatchMode && report.summary.result != BuildResult.Succeeded)
        {
            EditorApplication.Exit(1);
        }
    }

