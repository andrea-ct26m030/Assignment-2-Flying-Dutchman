    private static void CreateLights(Transform root, float radius)
    {
        Transform group = NewChild(root, "Party Lights", Vector3.zero);
        float height = 9f;

        // Three coloured spots above the floor, each aimed at its own third of the dance floor.
        for (int i = 0; i < 3; i++)
        {
            float angle = i * Mathf.PI * 2f / 3f;
            Vector3 direction = new Vector3(Mathf.Cos(angle), 0f, Mathf.Sin(angle));
            Transform t = NewChild(group, $"Disco Spot {i + 1}", direction * radius * 0.9f + Vector3.up * height);
            t.rotation = Quaternion.LookRotation(root.position + direction * radius * 0.35f - t.position);

            Light light = t.gameObject.AddComponent<Light>();
            light.type = LightType.Spot;
            light.spotAngle = 55f;
            light.innerSpotAngle = 30f;
            light.range = height * 2.5f;
            light.intensity = 30f;
            light.shadows = LightShadows.None;

            Configure(t.gameObject.AddComponent<PartyLight>(),
                ("beatsPerMinute", MusicBpm), ("hueOffset", i / 3f), ("hueSpeed", 0.12f), ("pulseDepth", 0.35f), ("beatOffset", i / 3f),
                ("sweepAngle", new Vector2(18f, 18f)), ("sweepSpeed", 0.9f + 0.2f * i));
        }

        // Two point lights circling low over the floor in opposite directions.
        for (int i = 0; i < 2; i++)
        {
            Transform t = NewChild(group, $"Disco Orbiter {i + 1}", Vector3.up * (2.5f + i));
            Light light = t.gameObject.AddComponent<Light>();
            light.type = LightType.Point;
            light.range = radius * 0.9f;
            light.intensity = 6f;
            light.shadows = LightShadows.None;

            Configure(t.gameObject.AddComponent<PartyLight>(),
                ("beatsPerMinute", MusicBpm), ("hueOffset", 0.5f * i + 0.15f), ("hueSpeed", 0.3f), ("pulseDepth", 0.5f), ("beatOffset", 0.5f * i),
                ("sweepAngle", Vector2.zero), ("orbitRadius", radius * 0.6f), ("orbitSpeed", i == 0 ? 1.2f : -0.8f));
        }

        // One strobe in the centre: kicks with the bass drum and "breathes" its range.
        Transform strobe = NewChild(group, "Disco Strobe", Vector3.up * 5f);
        Light strobeLight = strobe.gameObject.AddComponent<Light>();
        strobeLight.type = LightType.Point;
        strobeLight.range = radius;
        strobeLight.intensity = 8f;
        strobeLight.shadows = LightShadows.None;
        Configure(strobe.gameObject.AddComponent<PartyLight>(),
            ("beatsPerMinute", MusicBpm), ("hueOffset", 0.8f), ("hueSpeed", 0.05f), ("saturation", 0.35f), ("pulseDepth", 1f),
            ("rangePulse", 1.6f), ("sweepAngle", Vector2.zero));
    }

    private static void CreateParticles(Transform root, float radius)
    {
        Material glow = EnsureParticleMaterial(GlowMaterialPath, EnsureTexture(GlowTexturePath, 64, GlowPixel, false), true);
        Material confettiMaterial = EnsureParticleMaterial(ConfettiMaterialPath, null, false);
        Transform group = NewChild(root, "Party Particles", Vector3.zero);

        // 1) Confetti raining down on the whole dance floor.
        {
            ParticleSystem ps = NewParticleSystem(group, "Confetti", Vector3.up * 10f, confettiMaterial);
            ParticleSystem.MainModule main = ps.main;
            main.startLifetime = 7f;
            main.startSpeed = new ParticleSystem.MinMaxCurve(0.2f, 1f);
            main.startSize = new ParticleSystem.MinMaxCurve(0.08f, 0.2f);
            main.startRotation = new ParticleSystem.MinMaxCurve(0f, Mathf.PI * 2f);
            main.startColor = RandomColors(Color.magenta, Color.cyan, Color.yellow, new Color(1f, 0.4f, 0f), Color.green);
            main.gravityModifier = 0.12f;
            main.maxParticles = 1200;

            ParticleSystem.EmissionModule emission = ps.emission;
            emission.rateOverTime = 120f;

            ParticleSystem.ShapeModule shape = ps.shape;
            shape.shapeType = ParticleSystemShapeType.Box;
            shape.scale = new Vector3(radius * 2f, radius * 2f, 0.2f);
            shape.rotation = new Vector3(90f, 0f, 0f); // emit downwards

            ParticleSystem.RotationOverLifetimeModule rotation = ps.rotationOverLifetime;
            rotation.enabled = true;
            rotation.z = new ParticleSystem.MinMaxCurve(-4f, 4f);

            ParticleSystem.NoiseModule noise = ps.noise;
            noise.enabled = true;
            noise.strength = 0.6f;
            noise.frequency = 0.4f;

            FadeOut(ps, Color.white, Color.white);
        }

        // 2) Glowing sparkles drifting up from the floor.
        {
            ParticleSystem ps = NewParticleSystem(group, "Floor Sparkles", Vector3.up * 0.1f, glow);
            ParticleSystem.MainModule main = ps.main;
            main.startLifetime = new ParticleSystem.MinMaxCurve(3f, 5f);
            main.startSpeed = new ParticleSystem.MinMaxCurve(0.6f, 1.8f);
            main.startSize = new ParticleSystem.MinMaxCurve(0.15f, 0.5f);
            main.maxParticles = 500;

            ParticleSystem.EmissionModule emission = ps.emission;
            emission.rateOverTime = 60f;

            ParticleSystem.ShapeModule shape = ps.shape;
            shape.shapeType = ParticleSystemShapeType.Circle;
            shape.radius = radius;
            shape.rotation = new Vector3(-90f, 0f, 0f); // circle lies flat, particles rise
            shape.randomDirectionAmount = 0.15f;

            ParticleSystem.NoiseModule noise = ps.noise;
            noise.enabled = true;
            noise.strength = 0.8f;

            ParticleSystem.SizeOverLifetimeModule size = ps.sizeOverLifetime;
            size.enabled = true;
            size.size = new ParticleSystem.MinMaxCurve(1f, AnimationCurve.EaseInOut(0f, 1f, 1f, 0f));

            FadeOut(ps, Color.cyan, Color.magenta);
        }

        // 3) Four fountains at the edge firing bursts on the beat (120 BPM -> 0.5 s per beat).
        for (int i = 0; i < 4; i++)
        {
            float angle = (i + 0.5f) * Mathf.PI * 0.5f;
            Vector3 position = new Vector3(Mathf.Cos(angle), 0f, Mathf.Sin(angle)) * radius + Vector3.up * 0.2f;
            ParticleSystem ps = NewParticleSystem(group, $"Fountain {i + 1}", position, glow);
            ParticleSystem.MainModule main = ps.main;
            main.startLifetime = new ParticleSystem.MinMaxCurve(1.4f, 2.2f);
            main.startSpeed = new ParticleSystem.MinMaxCurve(8f, 13f);
            main.startSize = new ParticleSystem.MinMaxCurve(0.2f, 0.45f);
            main.startColor = RandomColors(new Color(1f, 0.85f, 0.3f), new Color(1f, 0.3f, 0.8f), Color.white);
            main.gravityModifier = 1.1f;
            main.maxParticles = 300;

            ParticleSystem.EmissionModule emission = ps.emission;
            emission.rateOverTime = 0f;
            SetFountainTiming(ps, i);

            ParticleSystem.ShapeModule shape = ps.shape;
            shape.shapeType = ParticleSystemShapeType.Cone;
            shape.angle = 10f;
            shape.radius = 0.15f;
            shape.rotation = new Vector3(-90f, 0f, 0f); // shoot upwards

            ParticleSystem.SizeOverLifetimeModule size = ps.sizeOverLifetime;
            size.enabled = true;
            size.size = new ParticleSystem.MinMaxCurve(1f, AnimationCurve.Linear(0f, 1f, 1f, 0.2f));

            FadeOut(ps, Color.white, new Color(1f, 0.5f, 0.1f));
        }
    }

    /// <summary>Fountain bursts every two beats; neighbouring fountains are one beat apart.</summary>
    private static void SetFountainTiming(ParticleSystem ps, int index)
    {
        float beat = 60f / MusicBpm;
        bool wasPlaying = ps.isPlaying;
        ps.Stop(true, ParticleSystemStopBehavior.StopEmittingAndClear); // duration can only be set while stopped
        ParticleSystem.MainModule main = ps.main;
        main.duration = beat * 4f;
        float offset = (index % 2) * beat;
        ParticleSystem.EmissionModule emission = ps.emission;
        emission.SetBursts(new[]
        {
            new ParticleSystem.Burst(offset, 45),
            new ParticleSystem.Burst(offset + beat * 2f, 45),
        });
        if (wasPlaying) ps.Play(true);
    }

    /// <summary>Loads the music clip and makes sure a long track is streamed and compressed.</summary>
    private static AudioClip LoadMusic()
    {
        AudioImporter importer = AssetImporter.GetAtPath(MusicPath) as AudioImporter;
        if (importer == null)
        {
            Debug.LogError($"Funky Town: music clip missing at {MusicPath}.");
            return null;
        }

        AudioImporterSampleSettings settings = importer.defaultSampleSettings;
        if (settings.loadType != AudioClipLoadType.Streaming || settings.compressionFormat != AudioCompressionFormat.Vorbis)
        {
            settings.loadType = AudioClipLoadType.Streaming;
            settings.compressionFormat = AudioCompressionFormat.Vorbis;
            settings.quality = 0.7f;
            importer.defaultSampleSettings = settings;
            importer.SaveAndReimport();
        }
        return AssetDatabase.LoadAssetAtPath<AudioClip>(MusicPath);
    }

    private static void CreateMusic(GameObject root, float radius)
    {
        AudioClip clip = LoadMusic();
        if (clip == null) return;

        AudioSource source = root.AddComponent<AudioSource>();
        source.clip = clip;
        source.loop = true;
        source.playOnAwake = true;
        source.volume = MusicVolume;
        source.spatialBlend = 1f;                      // fully 3D
        source.dopplerLevel = 0f;                      // no pitch bending while flying past
        source.rolloffMode = AudioRolloffMode.Linear;  // full volume inside min, silent beyond max
        source.minDistance = radius + 4f;
        source.maxDistance = 110f;
        source.spread = 60f;
    }

    private static void CreateCompass(Transform target)
    {
        SpaceshipController ship = Object.FindAnyObjectByType<SpaceshipController>();
        if (ship == null)
        {
            Debug.LogError("Funky Town: no SpaceshipController found, compass not created.");
            return;
        }

        // Remove compasses from earlier runs (including the old arrow on the world space canvas).
        foreach (Compass old in SceneManager.GetActiveScene().GetRootGameObjects()
                     .SelectMany(r => r.GetComponentsInChildren<Compass>(true)).ToList())
        {
            Object.DestroyImmediate(old.gameObject);
        }

        EnsureTexture(ArrowSpritePath, 256, ArrowPixel, true);
        EnsureTexture(DiscSpritePath, 256, DiscPixel, true);
        EnsureTexture(BlipSpritePath, 64, BlipPixel, true);

        // Own Screen Space - Overlay canvas next to the magazine, same scaling (constant pixel size).
        MagazineUI magazine = Object.FindAnyObjectByType<MagazineUI>();
        GameObject canvasObject = new GameObject(CompassName, typeof(RectTransform), typeof(Canvas), typeof(CanvasScaler));
        if (magazine != null && magazine.transform.parent != null)
        {
            canvasObject.transform.SetParent(magazine.transform.parent, false);
        }
        Canvas canvas = canvasObject.GetComponent<Canvas>();
        canvas.renderMode = RenderMode.ScreenSpaceOverlay;
        ApplyUiScaling();

        // Disc in the top-left corner, just below the row of bullet icons.
        const float size = 110f;
        RectTransform disc = NewImage(canvasObject.transform, "Disc", DiscSpritePath, new Color(1f, 1f, 1f, 0.85f), size);
        disc.anchorMin = disc.anchorMax = disc.pivot = new Vector2(0f, 1f);
        disc.anchoredPosition = new Vector2(20f, -65f);

        RectTransform arrow = NewImage(disc, "Arrow", ArrowSpritePath, new Color(0.2f, 1f, 0.9f), size * 0.32f);
        RectTransform blip = NewImage(disc, "Party Blip", BlipSpritePath, new Color(1f, 0.3f, 0.8f), size * 0.16f);

        Configure(canvasObject.AddComponent<Compass>(),
            ("target", target), ("ship", ship.transform), ("arrow", arrow), ("blip", blip),
            ("radarRange", 150f), ("discRadius", size * 0.5f - 9f));
        Debug.Log($"Funky Town: compass created (overlay canvas '{CompassName}', top-left below the magazine).");
    }

    /// <summary>
    /// Makes every Screen Space - Overlay canvas scale with the screen height instead of using a
    /// constant pixel size, so magazine and compass keep their relative size on high-resolution displays.
    /// </summary>
    private static void ApplyUiScaling()
    {
        foreach (Canvas canvas in SceneManager.GetActiveScene().GetRootGameObjects()
                     .SelectMany(r => r.GetComponentsInChildren<Canvas>(true)))
        {
            if (canvas.renderMode != RenderMode.ScreenSpaceOverlay || !canvas.isRootCanvas) continue;

            CanvasScaler scaler = canvas.GetComponent<CanvasScaler>();
            if (scaler == null) scaler = canvas.gameObject.AddComponent<CanvasScaler>();
            scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
            scaler.referenceResolution = UiReferenceResolution;
            scaler.screenMatchMode = CanvasScaler.ScreenMatchMode.MatchWidthOrHeight;
            scaler.matchWidthOrHeight = 1f; // follow the screen height
            EditorUtility.SetDirty(scaler);
        }
    }

    /// <summary>Creates a centred UI image as child of the given parent.</summary>
    private static RectTransform NewImage(Transform parent, string name, string spritePath, Color color, float size)
    {
        GameObject go = new GameObject(name, typeof(RectTransform), typeof(CanvasRenderer), typeof(Image));
        RectTransform rect = (RectTransform)go.transform;
        rect.SetParent(parent, false);
        rect.sizeDelta = new Vector2(size, size);
        Image image = go.GetComponent<Image>();
        image.sprite = AssetDatabase.LoadAssetAtPath<Sprite>(spritePath);
        image.color = color;
        image.raycastTarget = false;
        return rect;
    }

