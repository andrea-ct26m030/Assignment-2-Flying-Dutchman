    [MenuItem("Tools/Funky Town/1 Setup Party (lights, particles, music, compass)")]
    public static void SetupScene()
    {
        Scene scene = OpenScene();

        PartyGuestReaction party = Object.FindAnyObjectByType<PartyGuestReaction>();
        if (party == null)
        {
            Debug.LogError("Funky Town: no PartyGuestReaction (party platform) found in the scene.");
            return;
        }

        // The dance floor is derived from where the guests are standing.
        List<Transform> guests = party.GetComponentsInChildren<Animator>(true)
            .Where(a => a.GetComponentInChildren<SkinnedMeshRenderer>(true) != null)
            .Select(a => a.transform).ToList();

        Vector3 center;
        float radius;
        Transform parent;
        if (guests.Count > 0)
        {
            center = guests.Aggregate(Vector3.zero, (sum, g) => sum + g.position) / guests.Count;
            radius = Mathf.Clamp(guests.Max(g => Vector3.Distance(g.position, center)) + 1.5f, 4f, 20f);
            Transform first = guests[0].parent;
            parent = guests.All(g => g.parent == first) && first != null ? first : party.transform;
        }
        else
        {
            Bounds bounds = new Bounds(party.transform.position, Vector3.zero);
            foreach (MeshRenderer r in party.GetComponentsInChildren<MeshRenderer>(true)) bounds.Encapsulate(r.bounds);
            center = new Vector3(bounds.center.x, bounds.max.y, bounds.center.z);
            radius = Mathf.Clamp(Mathf.Max(bounds.extents.x, bounds.extents.z), 4f, 20f);
            parent = party.transform;
        }
        Debug.Log($"Funky Town: dance floor center {center}, radius {radius:F1}, {guests.Count} guests, parent '{parent.name}'.");

        // Replace anything generated by an earlier run.
        foreach (Transform old in parent.Cast<Transform>().Where(t => t.name == RootName).ToList())
        {
            Object.DestroyImmediate(old.gameObject);
        }

        GameObject root = new GameObject(RootName);
        root.transform.position = center;
        root.transform.SetParent(parent, true);

        CreateLights(root.transform, radius);
        CreateParticles(root.transform, radius);
        CreateMusic(root, radius);
        CreateCompass(party.transform);

        EditorSceneManager.MarkSceneDirty(scene);
        EditorSceneManager.SaveScene(scene);
        Debug.Log("Funky Town: party setup done.");
    }

    [MenuItem("Tools/Funky Town/1b Rebuild Compass + UI scaling")]
