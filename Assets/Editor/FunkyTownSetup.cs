    private static Scene OpenScene()
    {
        Scene active = SceneManager.GetActiveScene();
        return active.path == ScenePath ? active : EditorSceneManager.OpenScene(ScenePath, OpenSceneMode.Single);
    }

    /// <summary>True if the object (or a parent) is moved at runtime and must not be static.</summary>
    private static bool IsDynamic(Transform t)
    {
        if (t.GetComponentInParent<Animator>(true) != null) return true;
        if (t.GetComponentInParent<Animation>(true) != null) return true;
        if (t.GetComponentInParent<Rigidbody>(true) != null) return true;
        if (t.GetComponentInParent<Canvas>(true) != null) return true;
        if (t.GetComponentInParent<ParticleSystem>(true) != null) return true;
        if (t.GetComponentsInParent<MonoBehaviour>(true)
            .Any(m => m != null && m.GetType().Assembly.GetName().Name == "Assembly-CSharp")) return true;
        for (Transform p = t; p != null; p = p.parent)
        {
            if (p.name.Contains("SkyDome")) return true; // huge inverted sphere, would break occlusion
        }
        return false;
    }

    private static Transform NewChild(Transform parent, string name, Vector3 localPosition)
    {
        Transform t = new GameObject(name).transform;
        t.SetParent(parent, false);
        t.localPosition = localPosition;
        return t;
    }

    private static ParticleSystem NewParticleSystem(Transform parent, string name, Vector3 localPosition, Material material)
    {
        Transform t = NewChild(parent, name, localPosition);
        ParticleSystem ps = t.gameObject.AddComponent<ParticleSystem>();
        ParticleSystem.MainModule main = ps.main;
        main.loop = true;
        main.playOnAwake = true;
        main.simulationSpace = ParticleSystemSimulationSpace.World; // particles stay behind when the platform moves
        ParticleSystemRenderer renderer = t.GetComponent<ParticleSystemRenderer>();
        renderer.sharedMaterial = material;
        renderer.shadowCastingMode = ShadowCastingMode.Off;
        return ps;
    }

    private static ParticleSystem.MinMaxGradient RandomColors(params Color[] colors)
    {
        Gradient gradient = new Gradient { mode = GradientMode.Fixed };
        gradient.SetKeys(
            colors.Select((c, i) => new GradientColorKey(c, (i + 1f) / colors.Length)).ToArray(),
            new[] { new GradientAlphaKey(1f, 0f), new GradientAlphaKey(1f, 1f) });
        return new ParticleSystem.MinMaxGradient(gradient) { mode = ParticleSystemGradientMode.RandomColor };
    }

    private static void FadeOut(ParticleSystem ps, Color from, Color to)
    {
        ParticleSystem.ColorOverLifetimeModule color = ps.colorOverLifetime;
        color.enabled = true;
        Gradient gradient = new Gradient();
        gradient.SetKeys(
            new[] { new GradientColorKey(from, 0f), new GradientColorKey(to, 1f) },
            new[] { new GradientAlphaKey(0f, 0f), new GradientAlphaKey(1f, 0.1f), new GradientAlphaKey(1f, 0.7f), new GradientAlphaKey(0f, 1f) });
        color.color = gradient;
    }

    /// <summary>Sets private [SerializeField] fields of a component through SerializedObject.</summary>
    private static void Configure(Object component, params (string name, object value)[] fields)
    {
        SerializedObject so = new SerializedObject(component);
        foreach ((string name, object value) in fields)
        {
            SerializedProperty property = so.FindProperty(name);
            if (property == null)
            {
                Debug.LogError($"Funky Town: {component.GetType().Name} has no serialized field '{name}'.");
                continue;
            }
            switch (value)
            {
                case float f: property.floatValue = f; break;
                case Vector2 v: property.vector2Value = v; break;
                case Object o: property.objectReferenceValue = o; break;
                default: Debug.LogError($"Funky Town: unsupported value type for '{name}'."); break;
            }
        }
        so.ApplyModifiedPropertiesWithoutUndo();
    }

    private static Material EnsureParticleMaterial(string path, Texture2D texture, bool additive)
    {
        Material material = AssetDatabase.LoadAssetAtPath<Material>(path);
        if (material == null)
        {
            Shader shader = Shader.Find("Universal Render Pipeline/Particles/Unlit");
            if (shader == null)
            {
                Debug.LogError("Funky Town: URP particle shader not found.");
                return null;
            }
            material = new Material(shader);
            AssetDatabase.CreateAsset(material, path);
        }

        // Transparent surface; additive for the glow, alpha blended for the confetti.
        material.SetFloat("_Surface", 1f);
        material.SetFloat("_Blend", additive ? 2f : 0f);
        material.SetFloat("_SrcBlend", (float)BlendMode.SrcAlpha);
        material.SetFloat("_DstBlend", (float)(additive ? BlendMode.One : BlendMode.OneMinusSrcAlpha));
        material.SetFloat("_ZWrite", 0f);
        material.SetFloat("_Cull", (float)CullMode.Off);
        material.SetOverrideTag("RenderType", "Transparent");
        material.EnableKeyword("_SURFACE_TYPE_TRANSPARENT");
        material.renderQueue = (int)RenderQueue.Transparent;
        material.SetColor("_BaseColor", additive ? new Color(2f, 2f, 2f, 1f) : Color.white);
        if (texture != null) material.SetTexture("_BaseMap", texture);
        EditorUtility.SetDirty(material);
        return material;
    }

    private delegate Color PixelFunction(float u, float v);

    /// <summary>Creates a procedural PNG (if missing) and imports it as texture or sprite.</summary>
    private static Texture2D EnsureTexture(string path, int size, PixelFunction pixel, bool sprite)
    {
        if (!File.Exists(path))
        {
            Texture2D generated = new Texture2D(size, size, TextureFormat.RGBA32, false);
            for (int y = 0; y < size; y++)
            {
                for (int x = 0; x < size; x++)
                {
                    generated.SetPixel(x, y, pixel((x + 0.5f) / size, (y + 0.5f) / size));
                }
            }
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllBytes(path, generated.EncodeToPNG());
            Object.DestroyImmediate(generated);
            AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceSynchronousImport);
        }

        TextureImporter importer = (TextureImporter)AssetImporter.GetAtPath(path);
        TextureImporterType type = sprite ? TextureImporterType.Sprite : TextureImporterType.Default;
        bool spriteModeWrong = sprite && importer.spriteImportMode != SpriteImportMode.Single;
        if (importer.textureType != type || !importer.alphaIsTransparency || spriteModeWrong)
        {
            importer.textureType = type;
            if (sprite) importer.spriteImportMode = SpriteImportMode.Single; // project default would be Multiple
            importer.alphaIsTransparency = true;
            importer.mipmapEnabled = !sprite;
            importer.SaveAndReimport();
        }
        return AssetDatabase.LoadAssetAtPath<Texture2D>(path);
    }

    private static Color GlowPixel(float u, float v)
    {
        float d = Vector2.Distance(new Vector2(u, v), new Vector2(0.5f, 0.5f)) * 2f;
        float a = Mathf.Clamp01(1f - d);
        return new Color(1f, 1f, 1f, a * a);
    }

    private static Color ArrowPixel(float u, float v)
    {
        // Arrow head pointing up with a notch at the bottom.
        float x = Mathf.Abs(u - 0.5f);
        float outer = Mathf.InverseLerp(0.95f, 0.08f, v) * 0.38f; // half width of the outer triangle at height v
        float notch = Mathf.InverseLerp(0.32f, 0.08f, v) * 0.38f; // half width of the cut-out
        bool inside = v < 0.95f && v > 0.08f && x < outer && (v > 0.32f || x > notch);
        return inside ? Color.white : new Color(1f, 1f, 1f, 0f);
    }

    private static Color DiscPixel(float u, float v)
    {
        // Dark translucent disc with a bright rim, a faint inner ring and a tick at the top (= ahead).
        float d = Vector2.Distance(new Vector2(u, v), new Vector2(0.5f, 0.5f)) * 2f;
        if (d > 1f) return new Color(0f, 0f, 0f, 0f);
        Color rim = new Color(0.2f, 1f, 0.9f, 1f);
        if (d > 0.93f) return rim;
        if (Mathf.Abs(u - 0.5f) < 0.012f && v > 0.86f) return rim;
        if (Mathf.Abs(d - 0.5f) < 0.012f) return new Color(0.2f, 1f, 0.9f, 0.35f);
        return new Color(0.02f, 0.05f, 0.1f, 0.6f);
    }

    private static Color BlipPixel(float u, float v)
    {
        float d = Vector2.Distance(new Vector2(u, v), new Vector2(0.5f, 0.5f)) * 2f;
        return new Color(1f, 1f, 1f, Mathf.Clamp01((1f - d) * 6f));
    }

    private static Color DiscoBallPixel(float u, float v)
    {
        Vector2 p = new Vector2(u, v);
        float glow = Mathf.Clamp01(1f - Vector2.Distance(p, new Vector2(0.5f, 0.45f)) * 1.6f);
        Color background = Color.Lerp(new Color(0.07f, 0.03f, 0.13f), new Color(0.55f, 0.1f, 0.6f), glow * glow);

        // String the ball hangs on.
        if (Mathf.Abs(u - 0.5f) < 0.008f && v > 0.8f) background = new Color(0.8f, 0.8f, 0.85f);

        const float r = 0.36f;
        float nx = (u - 0.5f) / r, ny = (v - 0.45f) / r;
        float rr = nx * nx + ny * ny;
        if (rr > 1f) return background;

        // Mirror tiles in latitude / longitude on a sphere.
        float nz = Mathf.Sqrt(1f - rr);
        float lat = Mathf.Asin(ny);
        float lon = Mathf.Atan2(nx, nz);
        const float tiles = 7f;
        float tu = lon / Mathf.PI * tiles * 2f, tv = lat / Mathf.PI * tiles * 2f;
        float fu = Mathf.Abs(Mathf.Repeat(tu, 1f) - 0.5f), fv = Mathf.Abs(Mathf.Repeat(tv, 1f) - 0.5f);
        float hash = Mathf.Repeat(Mathf.Sin(Mathf.Floor(tu) * 12.9898f + Mathf.Floor(tv) * 78.233f) * 43758.5453f, 1f);

        float diffuse = Mathf.Clamp01(Vector3.Dot(new Vector3(nx, ny, nz), new Vector3(-0.45f, 0.55f, 0.7f).normalized));
        Color tile = Color.HSVToRGB(Mathf.Repeat(0.5f + hash * 0.45f, 1f), 0.35f + 0.4f * hash, 0.25f + 0.75f * diffuse);
        if (hash > 0.82f) tile = Color.Lerp(tile, Color.white, 0.8f); // sparkling tiles
        if (fu > 0.44f || fv > 0.44f) tile *= 0.35f;                  // gaps between tiles
        tile.a = 1f;
        return tile;
    }
